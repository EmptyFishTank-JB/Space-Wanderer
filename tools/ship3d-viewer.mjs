#!/usr/bin/env node
// Build the self-contained ship arrangement viewer from data/ship3d.json,
// data/ship.json, data/cameras.json and src/ship3d/geometry.js.
//   node tools/ship3d-viewer.mjs                 writes dev/ship3d.html
//   node tools/ship3d-viewer.mjs --fragment out  also writes a bare page fragment (no <html>/<head>) to `out`
import { readFileSync, writeFileSync } from 'node:fs';
import { checkArrangement, proposedChanges } from '../src/ship3d/geometry.js';

const root = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const ship = JSON.parse(read('data/ship3d.json'));
const sim = JSON.parse(read('data/ship.json'));
const cams = JSON.parse(read('data/cameras.json'));
const state = read('src/sim/state.js');

const report = checkArrangement(ship, sim);
const fuelCapacity = Number((/fuel:\s*\{[^}]*capacity:\s*([\d.]+)/.exec(state) || [])[1]) || null;
const SIM = {
  rooms: sim.rooms.filter((r) => !r.exterior).map(({ id, name, width, stations }) => ({ id, name, width, stations })),
  hatches: sim.hatches,
  fuelCapacity,
};
const REPORT = { ok: report.ok, problems: report.problems, volumes: report.volumes, resizes: report.resizes, changes: proposedChanges(report) };
const CAMYAW = Object.fromEntries(cams.feeds.filter((f) => f.room).map((f) => [f.room, f.yaw]));

const data = [
  `const SHIP = ${JSON.stringify(ship)};`,
  `const SIM = ${JSON.stringify(SIM)};`,
  `const REPORT = ${JSON.stringify(REPORT)};`,
  `const CAMYAW = ${JSON.stringify(CAMYAW)};`,
].join('\n');
const geometry = read('src/ship3d/geometry.js').replace(/^export /gm, '');
const fragment = read('tools/ship3d-viewer.template.html')
  .replace('/*__DATA__*/', () => data)
  .replace('/*__GEOMETRY__*/', () => geometry);

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- generated by tools/ship3d-viewer.mjs, do not edit -->
</head>
<body>
${fragment}
</body>
</html>
`;
writeFileSync(new URL('dev/ship3d.html', root), page);
const i = process.argv.indexOf('--fragment');
if (i > 0 && process.argv[i + 1]) writeFileSync(process.argv[i + 1], fragment);
console.log(`ship3d viewer built (${report.ok ? 'geometry consistent' : `${report.problems.length} problem(s)`})`);
